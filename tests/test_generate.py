import json
import tempfile
import unittest

from helpers import assert_links_resolve, make_brain, page, files_of, run_cli


class GenerateTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def gen(self, files):
        repo = make_brain(self.tmp.name, files)
        code, data, err = run_cli("generate", cwd=repo)
        self.assertEqual(code, 0, err)
        return repo / "brain", data

    def test_index_lists_type_folders_and_no_page(self):
        brain, data = self.gen(files_of(page("feature", "Approval", "summary: Approve invoices before posting")))
        index = (brain / "README.md").read_text()
        self.assertTrue(index.startswith("<!-- generated by pb; do not edit -->\n# Product brain"))
        self.assertIn("[AGENTS.md](AGENTS.md)", index)
        self.assertIn("- [Features](functional/features/README.md) — A user-facing capability of the product", index)
        self.assertIn("- [Open questions](open-questions/README.md) — ", index)
        folders = {t.split("/README.md")[0] for t in data["written"] if t.endswith("/README.md")}
        self.assertEqual(len([l for l in index.splitlines() if l.startswith("- [")]), len(folders))
        self.assertNotIn("Approval", index)
        order = [index.index(h) for h in ("## Functional", "## Technical", "## Decisions and questions")]
        self.assertEqual(order, sorted(order))

    def test_adding_a_page_changes_its_folder_readme_not_the_index(self):
        repo = make_brain(self.tmp.name, files_of(page("feature", "Approval")))
        run_cli("generate", cwd=repo)
        brain = repo / "brain"
        before = {p: p.read_text() for p in brain.rglob("README.md")}
        rel, text = page("decision", "Live", "area: ux\nstatus: accepted\ndate: 2026-10-31")
        (brain / rel).write_text(text)
        run_cli("generate", cwd=repo)
        after = {p: p.read_text() for p in brain.rglob("README.md")}
        self.assertEqual([p.relative_to(brain).as_posix() for p in after if after[p] != before[p]],
                         ["decisions/README.md"])
        self.assertIn("- [Live](Live.md) (accepted, 2026-10-31) — Body.", after[brain / "decisions/README.md"])

    def test_folder_readmes_list_pages_and_count_the_archived(self):
        brain, _ = self.gen(files_of(
            page("module", "Billing", "paths: [a/**]", "Owns invoices. Second sentence.\n"),
            page("decision", "Live", "area: ux\nstatus: accepted"),
            page("decision", "Old", "area: ux\nstatus: superseded\nupdated: 2026-01-01\narchived: true"),
            page("decision", "Recent old", "area: ux\nstatus: superseded\nupdated: 2026-10-01"),
            page("open-question", "Limits", "area: functional"),
            page("open-question", "Done", "area: ux\nstatus: resolved\nupdated: 2025-01-01\narchived: true"),
        ))
        modules = (brain / "technical/modules/README.md").read_text()
        self.assertTrue(modules.startswith("<!-- generated by pb; do not edit -->\n# Modules"))
        self.assertIn("[Brain index](../../README.md)", modules)
        self.assertIn("- [Billing](Billing.md) — Owns invoices.\n", modules)
        decisions = (brain / "decisions/README.md").read_text()
        self.assertIn("- [Live](Live.md) (accepted) — Body.", decisions)
        self.assertIn("- [Recent old](Recent%20old.md) (superseded)", decisions)
        self.assertNotIn("[Old]", decisions)
        self.assertIn("Archived: 1 pages (not listed).", decisions)
        self.assertLess(decisions.index("[Live]"), decisions.index("[Recent old]"))
        questions = (brain / "open-questions/README.md").read_text()
        self.assertIn("- [Limits](Limits.md) (functional) — Body.", questions)
        self.assertIn("Archived: 1 pages (not listed).", questions)
        self.assertIn("_none yet_", (brain / "technical/environments/README.md").read_text())

    def test_summaries_are_cut_on_visible_text_never_inside_a_link(self):
        url = "https://example.com/" + "very-long-path/" * 8
        brain, _ = self.gen(files_of(
            page("module", "Billing", "paths: [a/**]",
                 f"Calls [the registry]({url}) and [the tax office]({url}x) for every invoice it posts.\n"),
            page("module", "Ledger", "paths: [b/**]",
                 "References the [Società (S.r.l.) registry of every company that ever filed an invoice in the "
                 f"country]({url}) and then some more words that go well past the limit of the line.\n"),
        ))
        readme = (brain / "technical/modules/README.md").read_text()
        self.assertIn(f"- [Billing](Billing.md) — Calls [the registry]({url}) and [the tax office]({url}x) for every "
                      "invoice it posts.\n", readme)
        ledger = [l for l in readme.splitlines() if l.startswith("- [Ledger]")][0]
        self.assertTrue(ledger.endswith("…"), ledger)
        self.assertIn(f"[Società (S.r.l.) registry of every company that ever filed an invoice in the country]({url})",
                      ledger)

    def test_concepts_readme_is_the_glossary(self):
        brain, _ = self.gen(files_of(
            page("concept", "Invoice", "term_en: Invoice\nterm_it: Fattura\nsummary: A bill sent to a customer"),
            page("concept", "Approver", "term_en: Approver"),
        ))
        glossary = (brain / "functional/concepts/README.md").read_text()
        self.assertIn("# Glossary", glossary)
        self.assertIn("| English | Italian | Definition |", glossary)
        self.assertIn("| [Invoice](Invoice.md) | Fattura | A bill sent to a customer |", glossary)
        self.assertIn("| [Approver](Approver.md) | — |", glossary)
        self.assertLess(glossary.index("Approver"), glossary.index("Invoice"))
        self.assertEqual([p.name for p in brain.glob("*.md")], ["README.md"])

    def test_features_readme_is_the_catalogue_by_capability(self):
        brain, data = self.gen(files_of(
            page("role", "Accountant"),
            page("feature", "Approval", "capability: Invoicing\nstatus: released\nroles: [Accountant]\n"
                                        "summary: Approve invoices before posting"),
            page("feature", "Bulk send", "capability: Invoicing\nstatus: planned"),
            page("feature", "Export", "capability: Reporting\nstatus: idea"),
            page("feature", "Loose"),
        ))
        self.assertIn("functional/features/README.md", data["written"])
        catalogue = (brain / "functional/features/README.md").read_text()
        self.assertTrue(catalogue.startswith("<!-- generated by pb; do not edit -->\n# Product features"))
        self.assertIn("| [Approval](Approval.md) | released | [Accountant](../roles/Accountant.md) | "
                      "Approve invoices before posting |", catalogue)
        self.assertIn("| [Loose](Loose.md) | idea | — |", catalogue)
        order = [catalogue.index(h) for h in ("## Invoicing", "## Reporting", "## Uncategorised")]
        self.assertEqual(order, sorted(order))
        self.assertLess(catalogue.index("[Approval]"), catalogue.index("[Bulk send]"))
        self.assertEqual([p.name for p in brain.glob("*.md")], ["README.md"])

    def test_every_link_of_every_generated_file_resolves(self):
        brain, data = self.gen(dict(files_of(
            page("role", "Accountant"),
            page("concept", "Invoice", "term_en: Invoice",
                 "An [[Invoice]] is billed by [[Billing|the billing]].\n\n## Lifecycle\nDraft, sent.\n"),
            page("module", "Billing", "paths: [a/**]", "Owns [[Invoice#Lifecycle|invoices]].\n"),
            page("feature", "Invoice Approval", "roles: [Accountant]\nmodules: [Billing]\nconcepts: [Invoice]",
                 "An [[Accountant]] approves an [[Invoice]] in [[Billing]]; see [the glossary](../concepts/README.md)"
                 " and [docs](https://example.com).\n"),
            page("decision", "Single approver", "area: functional\naffects: [Invoice Approval]",
                 "Applies to [[Invoice Approval]].\n"),
        ), **{"AGENTS.md": "# Agents\n"}))
        generated = [brain / rel for rel in data["written"] if rel.endswith(".md")]
        self.assertIn(brain / ".pb/context/Invoice Approval.md", generated)
        links = assert_links_resolve(self, generated)
        self.assertGreater(links, 10)
        pack = (brain / ".pb/context/Invoice Approval.md").read_text()
        self.assertIn("[Accountant](../../functional/roles/Accountant.md)", pack)
        self.assertIn("[the glossary](../../functional/concepts/README.md)", pack)
        self.assertIn("[invoices](../../functional/concepts/Invoice.md#lifecycle)", pack)
        self.assertIn("[docs](https://example.com)", pack)

    def test_context_files_written_and_stale_removed(self):
        repo = make_brain(self.tmp.name, {
            **files_of(page("feature", "Approval"), page("module", "Billing", "paths: [a/**]")),
            ".pb/context/Gone.md": "old",
        })
        run_cli("generate", cwd=repo)
        ctx = repo / "brain" / ".pb" / "context"
        self.assertEqual(sorted(p.name for p in ctx.iterdir()), ["Approval.md"])
        self.assertIn("# Context: Approval", (ctx / "Approval.md").read_text())

    def test_process_reaches_the_pack_of_every_feature_it_goes_through(self):
        brain, _ = self.gen(files_of(
            page("role", "Accountant"),
            page("feature", "Ordering"),
            page("feature", "Invoicing"),
            page("feature", "Reports"),
            page("process", "Order to cash", 'roles: [Accountant]\napplies_to: [Ordering, Invoicing]',
                 "From order to payment.\n"),
            page("process", "Old close", 'status: retired\napplies_to: [Ordering]'),
        ))
        ctx = brain / ".pb" / "context"
        self.assertEqual(sorted(p.name for p in ctx.iterdir()), ["Invoicing.md", "Ordering.md", "Reports.md"])
        for name in ("Ordering.md", "Invoicing.md"):
            self.assertIn("## Processes\n\n### Order to cash", (ctx / name).read_text())
        self.assertNotIn("Old close", (ctx / "Ordering.md").read_text())
        self.assertNotIn("Order to cash", (ctx / "Reports.md").read_text())

    def test_backlinks(self):
        brain, _ = self.gen(files_of(
            page("module", "Billing", "paths: [a/**]"),
            page("decision", "D", 'area: technical\naffects: [Billing]', "See [[Billing]].\n"),
            page("feature", "F", 'modules: [Billing]'),
        ))
        data = json.loads((brain / ".pb" / "backlinks.json").read_text())
        self.assertEqual(data["Billing"], ["D", "F"])

    def test_generate_never_deletes_digests(self):
        brain, data = self.gen({".pb/digests/2020-01-01.md": "old", ".pb/digests/notes.md": "x"})
        self.assertTrue((brain / ".pb/digests/2020-01-01.md").exists())
        self.assertTrue((brain / ".pb/digests/notes.md").exists())
        self.assertEqual(data["deleted"], [])

    def test_generate_is_the_same_on_any_day(self):
        brain, _ = self.gen(files_of(
            page("decision", "Old", "area: ux\nstatus: superseded\nupdated: 2026-01-01")))
        decisions = (brain / "decisions/README.md").read_text()
        self.assertIn("[Old](Old.md) (superseded)", decisions)
        self.assertNotIn("Archived:", decisions)

    def test_archived_flag_passes_validate(self):
        repo = make_brain(self.tmp.name, files_of(
            page("decision", "Old", "area: ux\nstatus: superseded\narchived: true")))
        code, data, _ = run_cli("validate", cwd=repo)
        self.assertEqual(code, 0, data)
        self.assertEqual(data["errors"], [])
        self.assertNotIn("unknown-field", [w["code"] for w in data["warnings"]])

    def test_empty_brain_generate_and_stats(self):
        brain, data = self.gen({})
        self.assertIn("README.md", data["written"])
        code, stats, _ = run_cli("stats", cwd=brain.parent)
        self.assertEqual(code, 0)
        self.assertEqual((stats["pages"], stats["words"]), (0, 0))

    def test_generate_is_idempotent(self):
        repo = make_brain(self.tmp.name, files_of(page("feature", "Approval"), page("concept", "Invoice", "term_en: Invoice")))
        run_cli("generate", cwd=repo)
        first = {p: p.read_text() for p in (repo / "brain").rglob("*") if p.is_file()}
        run_cli("generate", cwd=repo)
        second = {p: p.read_text() for p in (repo / "brain").rglob("*") if p.is_file()}
        self.assertEqual(first, second)

    def test_broken_page_skipped(self):
        brain, _ = self.gen({**files_of(page("feature", "Approval")), "functional/features/Bad.md": "---\ntype: [\n---\n"})
        self.assertIn("[Approval](Approval.md)", (brain / "functional/features/README.md").read_text())


class StatsTest(unittest.TestCase):
    def test_stats_over_budget_and_largest(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = make_brain(tmp, files_of(
                page("concept", "Invoice", "term_en: Invoice", "w " * 300),
                page("feature", "Approval", "", "w " * 10),
                page("module", "Billing", "paths: [a/**]", "w " * 5),
            ))
            code, data, _ = run_cli("stats", cwd=repo)
            self.assertEqual(code, 0)
            self.assertEqual(data["pages"], 3)
            self.assertEqual(data["words"], 315)
            self.assertEqual(data["by_type"]["concept"], {"pages": 1, "words": 300})
            self.assertEqual(data["by_area"]["functional"], {"pages": 2, "words": 310})
            self.assertEqual(data["over_budget"], [{"title": "Invoice", "words": 300, "max": 250}])
            self.assertEqual([x["title"] for x in data["largest"]], ["Invoice", "Approval", "Billing"])


if __name__ == "__main__":
    unittest.main()
