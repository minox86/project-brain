import json
import tempfile
import unittest

from helpers import make_brain, page, files_of, run_cli


class GenerateTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def gen(self, files):
        repo = make_brain(self.tmp.name, files)
        code, data, err = run_cli("generate", cwd=repo)
        self.assertEqual(code, 0, err)
        return repo / "brain", data

    def test_index_groups_and_archives(self):
        brain, _ = self.gen(files_of(
            page("feature", "Approval", "summary: Approve invoices before posting"),
            page("module", "Billing", "paths: [a/**]", "Owns invoices. Second sentence.\n"),
            page("decision", "Live", "area: ux\nstatus: accepted"),
            page("decision", "Old", "area: ux\nstatus: superseded\nupdated: 2026-01-01\narchived: true"),
            page("decision", "Recent old", "area: ux\nstatus: superseded\nupdated: 2026-10-01"),
            page("open-question", "Done", "area: ux\nstatus: resolved\nupdated: 2025-01-01\narchived: true"),
        ))
        index = (brain / "index.md").read_text()
        self.assertTrue(index.startswith("<!-- generated by pb; do not edit -->"))
        self.assertIn("## Functional", index)
        self.assertIn("- [[Approval]] — Approve invoices before posting", index)
        self.assertIn("- [[Billing]] — Owns invoices.", index)
        self.assertIn("- [[Live]] (accepted)", index)
        self.assertIn("[[Recent old]] (superseded)", index)
        self.assertNotIn("[[Old]]", index)
        self.assertNotIn("[[Done]]", index)
        self.assertIn("Archived: 2 pages (not listed).", index)
        self.assertLess(index.index("## Functional"), index.index("## Technical"))
        self.assertLess(index.index("## Decisions"), index.index("## Open questions"))

    def test_glossary_bilingual_sorted(self):
        brain, _ = self.gen(files_of(
            page("concept", "Invoice", "term_en: Invoice\nterm_it: Fattura\nsummary: A bill sent to a customer"),
            page("concept", "Approver", "term_en: Approver"),
        ))
        glossary = (brain / "glossary.md").read_text()
        self.assertIn("| English | Italian | Definition |", glossary)
        self.assertIn("| [[Invoice\\|Invoice]] | Fattura | A bill sent to a customer |", glossary)
        self.assertIn("| [[Approver\\|Approver]] | — |", glossary)
        self.assertLess(glossary.index("Approver"), glossary.index("Invoice"))

    def test_feature_catalogue_by_capability(self):
        brain, data = self.gen(files_of(
            page("role", "Accountant"),
            page("feature", "Approval", 'capability: Invoicing\nstatus: released\nroles: ["[[Accountant]]"]\n'
                                        "summary: Approve invoices before posting"),
            page("feature", "Bulk send", "capability: Invoicing\nstatus: planned"),
            page("feature", "Export", "capability: Reporting\nstatus: idea"),
            page("feature", "Loose"),
        ))
        self.assertIn("features.md", data["written"])
        catalogue = (brain / "features.md").read_text()
        self.assertTrue(catalogue.startswith("<!-- generated by pb; do not edit -->"))
        self.assertIn("| [[Approval]] | released | [[Accountant]] | Approve invoices before posting |", catalogue)
        self.assertIn("| [[Loose]] | idea | — |", catalogue)
        order = [catalogue.index(h) for h in ("## Invoicing", "## Reporting", "## Uncategorised")]
        self.assertEqual(order, sorted(order))
        self.assertLess(catalogue.index("[[Approval]]"), catalogue.index("[[Bulk send]]"))
        self.assertIn("(features.md)", (brain / "index.md").read_text())

    def test_context_files_written_and_stale_removed(self):
        repo = make_brain(self.tmp.name, {
            **files_of(page("feature", "Approval"), page("module", "Billing", "paths: [a/**]")),
            "context/Gone.md": "old",
        })
        run_cli("generate", cwd=repo)
        ctx = repo / "brain" / "context"
        self.assertEqual(sorted(p.name for p in ctx.iterdir()), ["Approval.md"])
        self.assertIn("# Context: Approval", (ctx / "Approval.md").read_text())

    def test_backlinks(self):
        brain, _ = self.gen(files_of(
            page("module", "Billing", "paths: [a/**]"),
            page("decision", "D", 'area: technical\naffects: ["[[Billing]]"]', "See [[Billing]].\n"),
            page("feature", "F", 'modules: ["[[Billing]]"]'),
        ))
        data = json.loads((brain / ".pb" / "backlinks.json").read_text())
        self.assertEqual(data["Billing"], ["D", "F"])

    def test_generate_never_deletes_digests(self):
        brain, data = self.gen({"digests/2020-01-01.md": "old", "digests/notes.md": "x"})
        self.assertTrue((brain / "digests/2020-01-01.md").exists())
        self.assertTrue((brain / "digests/notes.md").exists())
        self.assertEqual(data["deleted"], [])

    def test_generate_is_the_same_on_any_day(self):
        brain, _ = self.gen(files_of(
            page("decision", "Old", "area: ux\nstatus: superseded\nupdated: 2026-01-01")))
        index = (brain / "index.md").read_text()
        self.assertIn("[[Old]] (superseded)", index)
        self.assertNotIn("Archived:", index)

    def test_archived_flag_passes_validate(self):
        repo = make_brain(self.tmp.name, files_of(
            page("decision", "Old", "area: ux\nstatus: superseded\narchived: true")))
        code, data, _ = run_cli("validate", cwd=repo)
        self.assertEqual(code, 0, data)
        self.assertEqual(data["errors"], [])
        self.assertNotIn("unknown-field", [w["code"] for w in data["warnings"]])

    def test_empty_brain_generate_and_stats(self):
        brain, data = self.gen({})
        self.assertIn("index.md", data["written"])
        code, stats, _ = run_cli("stats", cwd=brain.parent)
        self.assertEqual(code, 0)
        self.assertEqual((stats["pages"], stats["words"]), (0, 0))

    def test_generate_is_idempotent(self):
        repo = make_brain(self.tmp.name, files_of(page("feature", "Approval"), page("concept", "Invoice", "term_en: Invoice")))
        run_cli("generate", cwd=repo)
        first = {p: p.read_text() for p in (repo / "brain").rglob("*") if p.is_file()}
        run_cli("generate", cwd=repo)
        second = {p: p.read_text() for p in (repo / "brain").rglob("*") if p.is_file()}
        self.assertEqual(first, second)

    def test_broken_page_skipped(self):
        brain, _ = self.gen({**files_of(page("feature", "Approval")), "functional/features/Bad.md": "---\ntype: [\n---\n"})
        self.assertIn("[[Approval]]", (brain / "index.md").read_text())


class StatsTest(unittest.TestCase):
    def test_stats_over_budget_and_largest(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = make_brain(tmp, files_of(
                page("concept", "Invoice", "term_en: Invoice", "w " * 300),
                page("feature", "Approval", "", "w " * 10),
                page("module", "Billing", "paths: [a/**]", "w " * 5),
            ))
            code, data, _ = run_cli("stats", cwd=repo)
            self.assertEqual(code, 0)
            self.assertEqual(data["pages"], 3)
            self.assertEqual(data["words"], 315)
            self.assertEqual(data["by_type"]["concept"], {"pages": 1, "words": 300})
            self.assertEqual(data["by_area"]["functional"], {"pages": 2, "words": 310})
            self.assertEqual(data["over_budget"], [{"title": "Invoice", "words": 300, "max": 250}])
            self.assertEqual([x["title"] for x in data["largest"]], ["Invoice", "Approval", "Billing"])


if __name__ == "__main__":
    unittest.main()
